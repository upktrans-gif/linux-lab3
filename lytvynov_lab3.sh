#!/bin/bash

# [ЗАВДАННЯ 1] Виведіть PID поточного процесу shell.
echo $$
# Пояснення: Спеціальна змінна $$ у Bash зберігає унікальний ідентифікатор (PID) поточного процесу оболонки (shell), у якій виконується скрипт чи команда. Вона підходить найкраще, оскільки повертає PID миттєво без виклику зовнішніх утиліт.

# [ЗАВДАННЯ 2] Виведіть список усіх запущених процесів поточного користувача.
ps -u "$USER"
# Пояснення: Команда ps із прапорцем -u виводить інформацію про активні процеси конкретного користувача, ім'я якого береться зі змінної середовища $USER. Цей варіант зручний для швидкої фільтрації процесів без ручного пошуку.

# [ЗАВДАННЯ 3] Виведіть 5 найбільш ресурсоємних процесів за споживанням пам’яті.
ps aux --sort=-%mem | head -n 6
# Пояснення: Команда ps aux показує всі процеси в системі, параметр --sort=-%mem сортує їх за спаданням використання оперативної пам'яті, а утиліта head -n 6 виводить заголовок таблиці та перші 5 процесів.

# [ЗАВДАННЯ 4] Знайдіть усі процеси, пов’язані зі службою або програмою cron.
pgrep -af cron
# Пояснення: Утиліта pgrep шукає активні процеси за назвою (cron). Прапорець -a виводить повний командний рядок разом із PID, а -f дозволяє шукати збіги по всьому рядку запуску процесу.

# [ЗАВДАННЯ 5] Створіть файл monitor.sh і надайте йому права на виконання лише для власника.
touch monitor.sh && chmod 700 monitor.sh
# Пояснення: Команда touch створює порожній файл monitor.sh, а chmod 700 встановлює права rwx------ (читання, запис і виконання лише для власника файлу та заборона доступу для групи й інших користувачів).

# [ЗАВДАННЯ 6] Виведіть список усіх активних служб (state=active).
systemctl list-units --type=service --state=active
# Пояснення: Утиліта systemctl керує системними службами systemd. Параметр --type=service обмежує вивід лише сервісами, а --state=active фільтрує тільки ті служби, які зараз працюють.

# [ЗАВДАННЯ 7] Виведіть останні 30 рядків журналу системних повідомлень.
journalctl -n 30
# Пояснення: Команда journalctl читає системний журнал systemd, а прапорець -n 30 (lines) обмежує вивід останніми 30 записами, що дозволяє швидко переглянути свіжі події та помилки.

# [ЗАВДАННЯ 8] Перевірте, чи активна служба cron. Якщо так, виведіть повідомлення “cron працює”, інакше — виведіть повідомлення “cron не працює”.
if systemctl is-active --quiet cron; then echo "cron працює"; else echo "cron не працює"; fi
# Пояснення: Команда systemctl is-active --quiet перевіряє статус служби cron без виведення зайвого тексту в консоль і повертає код 0, якщо служба активна. Конструкція if-else аналізує цей код і виводить відповідне повідомлення.

# [ЗАВДАННЯ 9] Виведіть 5 найбільш ресурсоємних процесів за використанням пам’яті, збережіть результат у файл mem_top.log, і запустіть команду зі зниженим пріоритетом у фоновому режимі.
nice -n 10 ps aux --sort=-%mem | head -n 6 > mem_top.log &
# Пояснення: Утиліта nice -n 10 знижує пріоритет виконання команди (збільшує значення niceness), перенаправлення > зберігає результат у файл mem_top.log, а символ & у кінці запускає весь процес у фоновому режимі.

# [ЗАВДАННЯ 10] Запишіть поточну дату й час у файл .log.
date >> system_time.log
# Пояснення: Команда date повертає поточні системні дату та час, а оператор >> дописує їх у кінець файлу з розширенням .log, не видаляючи попередні записи журналу.
