#!/bin/bash

# Зберігаємо перший переданий аргумент у змінну username
username="$1"

# 1. Перевіряємо, чи передано аргумент (чи не порожній рядок)
if [ -z "$username" ]; then
    echo "Помилка: не вказано ім'я користувача."
    echo "Використання: $0 <ім'я_користувача>"
    exit 1
fi

# 2. Перевіряємо, чи існує такий користувач у системі
if ! id "$username" &>/dev/null; then
    echo "Помилка: користувача '$username' не знайдено в системі."
    exit 1
fi

echo "=== Інформація про процеси користувача: $username ==="

# 3. Виводимо всі активні процеси цього користувача
ps -u "$username"

# 4. Підраховуємо кількість процесів користувача
proc_count=$(ps -u "$username" --no-headers | wc -l)
echo "--------------------------------------------------"
echo "Загальна кількість активних процесів користувача $username: $proc_count"

# Перевіряємо, чи перевищує кількість процесів поріг у 50
if [ "$proc_count" -gt 50 ]; then
    echo "ПОПЕРЕДЖЕННЯ: у користувача $username запущено понад 50 процесів ($proc_count)!"
fi

# 5. Зберігаємо 3 найбільш «важкі» процеси користувача (за пам’яттю) у файл
log_file="top_proc_${username}.log"
ps -u "$username" -o pid,user,%mem,%cpu,comm --sort=-%mem | head -n 4 > "$log_file"

echo "Топ-3 процеси за використанням пам'яті збережено у файл: $log_file"
